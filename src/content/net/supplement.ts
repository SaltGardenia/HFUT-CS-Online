export const isNetSupplementAnchor = (anchor: string) => /^sec-ch[1-8]-supp-/.test(anchor);
export function buildNetSupplement(original: DeckData): DeckData {
  const no = Number(original.id.slice(2));
  const sections: Section[] = (supplements[no] ?? []).map(([key, heading, html]) => ({
    id: 'sec-ch'+no+'-supp-'+key, heading, blocks: [{type:'html',html}],
  }));
  return {...original, lede:'<p>本页收录历年试题涉及而未在课件主线详细展开的考点，以及必要的现代技术补充。复习时与课件主线区分，不将此处知识自动视为本届考试重点。</p>', sections,
    toc: sections.map(s => ({id:s.id,text:s.heading,level:2}))};
}
